"""
Runs every experiment in the laboratory and writes results.md.

    Task 3 : Tests 1-4
    Task 5 : BFS vs A* on the (unchanged) warehouse
    Task 6 : heuristic investigation (Manhattan, h=0, Euclidean, 2 x Manhattan)
             on the warehouse, plus two extra maps that make the effects visible

Run:
    python experiments.py
"""

import os

from search_agent import parse_map, astar, bfs, HEURISTICS, manhattan

HERE = os.path.dirname(os.path.abspath(__file__))


def load(name):
    with open(os.path.join(HERE, "maps", name)) as f:
        return parse_map(f.read())


def fmt(r):
    return ("yes" if r.found else "no",
            str(r.path_length) if r.found else "-",
            str(r.expanded))


def table(header, rows):
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(out)


def block(text):
    return "```\n" + text + "\n```"


def main():
    md = ["# Experiment results (generated by `experiments.py`)\n",
          "States expanded = states removed from the frontier and expanded "
          "(goal test on removal; the goal itself is not counted). "
          "A* ties on f are broken by smaller h, then insertion order.\n"]

    # ---------------- Task 3 -------------------------------------------
    md.append("## Task 3: Testing the A* program (Manhattan heuristic)\n")
    tests = [("Test 1: original warehouse", "warehouse.txt"),
             ("Test 2: trivial (goal adjacent)", "test2_trivial.txt"),
             ("Test 3: no solution", "test3_no_solution.txt"),
             ("Test 4: alternative paths (14 vs 16 moves)",
              "test4_alternative_paths.txt"),
             ("Test 4b: many equal shortest paths", "test4b_many_equal_paths.txt")]
    rows = []
    for title, f in tests:
        g = load(f)
        r = astar(g, manhattan)
        b = bfs(g)
        rows.append((title, *fmt(r), str(b.path_length) if b.found else "-"))
        md.append(f"### {title}\n")
        md.append("Map:\n\n" + block("\n".join(g.rows)) + "\n")
        md.append("Program output:\n\n" + block(r.report(g)) + "\n")
    md.append("### Summary\n")
    md.append(table(["Test", "Path found", "Path length", "States expanded",
                     "Shortest length (independent BFS check)"], rows) + "\n")

    # ---------------- Task 5 -------------------------------------------
    md.append("## Task 5: A* vs BFS on the same warehouse\n")
    g = load("warehouse.txt")
    b, a = bfs(g), astar(g, manhattan)
    md.append(table(["Measure", "BFS", "A*"], [
        ("Solution found", fmt(b)[0], fmt(a)[0]),
        ("Path length", fmt(b)[1], fmt(a)[1]),
        ("States expanded", fmt(b)[2], fmt(a)[2]),
        ("States generated (added to frontier)", str(b.generated), str(a.generated)),
    ]) + "\n")
    free = sum(ch != "#" for row in g.rows for ch in row)
    md.append(f"Free cells in the warehouse: {free} (all reachable from S).\n")
    md.append("BFS path:\n\n" + block(g.render(b.path)) + "\n")
    md.append("A* path:\n\n" + block(g.render(a.path)) + "\n")

    md.append("### Extra: the same comparison on an open warehouse "
              "(`maps/open_warehouse.txt`)\n")
    g2 = load("open_warehouse.txt")
    b2, a2 = bfs(g2), astar(g2, manhattan)
    md.append(table(["Measure", "BFS", "A*"], [
        ("Solution found", fmt(b2)[0], fmt(a2)[0]),
        ("Path length", fmt(b2)[1], fmt(a2)[1]),
        ("States expanded", fmt(b2)[2], fmt(a2)[2]),
    ]) + "\n")

    # ---------------- Task 6 -------------------------------------------
    md.append("## Task 6: Heuristic investigation\n")
    names = {"manhattan": "Manhattan (abs(dx) + abs(dy))",
             "zero": "h(n) = 0",
             "euclidean": "Euclidean (sqrt(dx^2 + dy^2))",
             "manhattan_x2": "2 x Manhattan"}
    for title, f in [("Laboratory warehouse", "warehouse.txt"),
                     ("Open warehouse", "open_warehouse.txt"),
                     ("Two-route map (Test 4)", "test4_alternative_paths.txt")]:
        g = load(f)
        opt = bfs(g).path_length
        rows = []
        for k, h in HEURISTICS.items():
            r = astar(g, h)
            rows.append((names[k], *fmt(r),
                         "yes" if r.path_length == opt else "NO"))
        md.append(f"### {title} (optimal length {opt})\n")
        md.append(table(["Heuristic", "Solution found", "Path length",
                         "States expanded", "Optimal?"], rows) + "\n")
        if f == "test4_alternative_paths.txt":
            md.append("Path returned with 2 x Manhattan:\n\n" +
                      block(g.render(astar(g, HEURISTICS['manhattan_x2']).path)) + "\n")
            md.append("Path returned with Manhattan:\n\n" +
                      block(g.render(astar(g, manhattan).path)) + "\n")

    out = "\n".join(md)
    with open(os.path.join(HERE, "results.md"), "w") as fh:
        fh.write(out)
    print(out)


if __name__ == "__main__":
    main()
